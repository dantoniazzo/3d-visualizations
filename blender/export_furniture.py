def main():
    os.makedirs(OUT, exist_ok=True)
    items = []
    # `-- <prefix>...` rebuilds only the pieces whose ids start with one of
    # them; every other piece keeps its GLB and its entry as they were.
    only = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    try:
        with open(os.path.join(OUT, "catalog.json")) as f:
            before = {i["id"]: i for i in json.load(f)["items"]}
    except (OSError, ValueError, KeyError):
        before = {}

    for piece_id, label, category, build, *rest in PIECES:
        # A trailing string is the anchor; a dict, more catalogue fields
        # (e.g. {"collision": "mesh"} for a piece over the app's budget whose
        # box would wall off floor it doesn't cover, like an L-shaped sofa).
        anchor = next((r for r in rest if isinstance(r, str)), "floor")
        extra = next((r for r in rest if isinstance(r, dict)), {})
        if only and not any(piece_id.startswith(p) for p in only) and piece_id in before:
            items.append(before[piece_id])
            continue
        fresh()
        mats = m.library()
        col = g.collection("piece")

        # Its doors and drawers are parts of their own, which the app opens
        # (geometry.join_piece).
        obj = g.join_piece(build(col, mats), piece_id, col)
        if obj is None:
            print(f"SKIP {piece_id}")
            continue

        # Centre on the footprint and stand it on the floor, so a placement
        # position means "put it here" rather than "put its origin here".
        corners = [g.bounds(o) for o in [obj, *obj.children] if o.type == "MESH"]
        lo = g.Vector([min(c[0][k] for c in corners) for k in range(3)])
        hi = g.Vector([max(c[1][k] for c in corners) for k in range(3)])
        shift = ((lo.x + hi.x) / 2, (lo.y + hi.y) / 2, lo.z)
        for v in obj.data.vertices:
            v.co.x -= shift[0]
            v.co.y -= shift[1]
            v.co.z -= shift[2]
        obj.data.update()
        for child in obj.children:
            child.location.x -= shift[0]
            child.location.y -= shift[1]
            child.location.z -= shift[2]
        # A lamp's lights, moved with it, as the node extras the app reads.
        LD.place_lights(obj, shift)

        bake_tiling_textures()

        bpy.ops.export_scene.gltf(
            filepath=os.path.join(OUT, f"{piece_id}.glb"),
            export_format="GLB",
            use_visible=True,
            export_apply=True,
            export_cameras=False,
            export_lights=False,
            # What each door or drawer does (geometry.join_piece), as its node's extras.
            export_extras=True,
            export_yup=True,
            export_image_format="WEBP",
            export_image_quality=60,
        )

        size = [round(hi.x - lo.x, 2), round(hi.z - lo.z, 2), round(hi.y - lo.y, 2)]
        kb = os.path.getsize(os.path.join(OUT, f"{piece_id}.glb")) / 1024
        print(f"  {kb:6.0f} KB  {piece_id:18s} {size}")

        items.append({
            "id": piece_id,
            "name": label,
            "category": category,
            "url": f"/models/furniture/{piece_id}.glb",
            "scale": 1,
            "yaw": 0,
            # Reported x, y, z with y up, matching the app's axes.
            "size": size,
            "anchor": anchor,
            "credit": "Built procedurally by blender/export_furniture.py",
            "enabled": True,
            **extra,
        })

    catalog = {
        "$comment": "Generated by blender/export_furniture.py — `npm run furniture`. "
                    "Add your own .glb files here and append entries in the same shape.",
        "categories": CATEGORIES,
        "items": items,
    }
    with open(os.path.join(OUT, "catalog.json"), "w") as f:
        json.dump(catalog, f, indent=4)
    print(f"CATALOG {len(items)} items")


main()
